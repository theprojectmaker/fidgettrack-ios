// Turns web/index.html (the exact offline PWA) into src/page.js, the HTML string the native
// WebView loads. The page already talks to the native shell when it runs inside it, so the
// only changes are dropping the PWA-only <head> links, which would 404 in the WebView.
// Run: node tools/build-native.mjs   (commit the generated src/page.js)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let html = fs.readFileSync(path.join(root, 'web', 'index.html'), 'utf8');

for (const tag of ['<link rel="manifest" href="manifest.webmanifest" />\n', '<link rel="apple-touch-icon" href="icon-192.png" />\n']) {
  if (!html.includes(tag)) throw new Error('build-native: expected tag not found: ' + tag.trim());
  html = html.replace(tag, '');
}
if (!html.includes('window.ReactNativeWebView')) throw new Error('build-native: web/index.html has no native bridge');

fs.writeFileSync(path.join(root, 'src', 'page.js'), '// Generated by tools/build-native.mjs from web/index.html. Do not edit by hand.\nmodule.exports = ' + JSON.stringify(html) + ';\n');
console.log('Wrote src/page.js (' + html.length + ' chars) from web/index.html');
