// Turns web/index.html (the exact offline PWA) into src/page.js — the HTML the
// native WebView loads as a string. It injects a small native-bridge layer so the
// app uses iOS local notifications for reminders and the system camera for scanning.
// Run: node tools/build-native.mjs   (commit the generated src/page.js)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(dir, '..');
let html = fs.readFileSync(path.join(root, 'web', 'index.html'), 'utf8');

const replace = (needle, repl) => {
  if (!html.includes(needle)) throw new Error('build-native: anchor not found:\n' + needle.slice(0, 120));
  html = html.replace(needle, repl);
};
const remove = (needle) => { if (html.includes(needle)) html = html.replace(needle, ''); };

// 1) Drop PWA-only <head> links that would 404 inside the WebView.
remove('<link rel="manifest" href="manifest.webmanifest" />\n');
remove('<link rel="apple-touch-icon" href="icon-192.png" />\n');

// 2) Scan: in the native shell, use the system camera via the file input (reliable
//    in WKWebView) instead of getUserMedia.
replace(
  "  const video=$('#cam'); const hint=$('#scanHint');\n  const hasCam =",
  "  const video=$('#cam'); const hint=$('#scanHint');\n" +
  "  if(window.__FT_NATIVE){ video.classList.add('hidden'); hint.textContent='Tap the shutter to snap a photo'; scanMode='file';" +
  " $('#shutterBtn').onclick=()=>{photoTarget='scan';$('#fileCam').click();};" +
  " $('#pickPhotoBtn').onclick=()=>{photoTarget='scan';$('#fileCam').click();}; return; }\n" +
  "  const hasCam ="
);

// 3) Web Notification API doesn't exist in WKWebView — native handles reminders.
replace(
  "function checkReminders(){\n  if(!S.settings.notify",
  "function checkReminders(){\n  if(window.__FT_NATIVE) return;\n  if(!S.settings.notify"
);

// 4) Enabling reminders asks iOS for permission through the bridge.
replace(
  "async function enableNotifications(){\n  if(!('Notification' in window))",
  "async function enableNotifications(){\n  if(window.__FT_NATIVE){ window.__ftPost&&window.__ftPost({type:'requestNotifications'}); return; }\n  if(!('Notification' in window))"
);

// 5) "Remind" button fires an immediate iOS notification natively.
replace(
  "  const f=fidgetById(l.fidgetId),p=personById(l.personId);\n  if(S.settings.notify && Notification.permission==='granted'){",
  "  const f=fidgetById(l.fidgetId),p=personById(l.personId);\n  if(window.__FT_NATIVE){ window.__ftPost&&window.__ftPost({type:'remindNow',fidgetId:l.fidgetId,title:'Collect your fidget',body:'\"'+f.name+'\" — '+p.name+' has it.'}); toast('Reminder sent','bell'); return; }\n  if(S.settings.notify && Notification.permission==='granted'){"
);

// 6) Push the current reminder set to native on every render (idempotent).
replace(
  "  bindDynamic();\n}\nfunction renderTabs(){",
  "  bindDynamic();\n  if(window.__FT_NATIVE&&window.syncNative) window.syncNative();\n}\nfunction renderTabs(){"
);

// 7) The native bridge itself.
const BRIDGE = `
<script>
(function(){
  if(!window.ReactNativeWebView) return;
  window.__FT_NATIVE=true;
  function post(m){try{window.ReactNativeWebView.postMessage(JSON.stringify(m));}catch(e){}}
  window.__ftPost=post;
  window.syncNative=function(){try{post({type:'reminders',
    fidgets:S.fidgets.map(function(f){return{id:f.id,name:f.name};}),
    people:S.people.map(function(p){return{id:p.id,name:p.name};}),
    loans:S.loans.map(function(l){return{id:l.id,fidgetId:l.fidgetId,personId:l.personId,dueAt:l.dueAt,status:l.status};})
  });}catch(e){}};
  window.__ftNative=function(msg){try{
    if(!msg)return;
    if(msg.type==='notifState'){S.settings.notify=!!msg.granted; if(typeof saveSettings==='function')saveSettings(); if(typeof render==='function')render();}
    else if(msg.type==='openFidget'){ if(typeof fidgetById==='function'&&fidgetById(msg.fidgetId)) go('fidget',msg.fidgetId);}
  }catch(e){}};
  post({type:'notifQuery'});
})();
</script>`;
replace("</script>\n</body>\n</html>", "</script>" + BRIDGE + "\n</body>\n</html>");

const out = '// Generated by tools/build-native.mjs from web/index.html. Do not edit by hand.\n' +
  'module.exports = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'page.js'), out);
console.log('Wrote src/page.js (' + out.length + ' bytes) from web/index.html');
